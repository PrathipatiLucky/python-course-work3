

hr = int(input("Enter the time: "))

if 5<= hr <=11:
    print("Good Morning")
elif 12 <= hr <=16:
    print("Good Afternoon")
elif 17 <= hr <=20:
    print("Good Evening")
elif 21 <= hr <=24:
    print("Good Night")
else:
    print("Mid Night Sleep well")

